/**
 * Localization system — provides translated strings based on selected language.
 * Supports: English, فارسی, 中文, 日本語, 한국어, Español
 */
object Locales {

    fun getString(key: String, lang: String): String {
        return when (lang) {
            "fa" -> fa[key] ?: en[key] ?: key
            "zh" -> zh[key] ?: en[key] ?: key
            "ja" -> ja[key] ?: en[key] ?: key
            "ko" -> ko[key] ?: en[key] ?: key
            "es" -> es[key] ?: en[key] ?: key
            else -> en[key] ?: key
        }
    }

    /** Get localized weapon name by WeaponType name */
    fun getWeaponName(weaponName: String, lang: String): String {
        val key = "weapon_${weaponName.lowercase()}"
        return getString(key, lang)
    }

    /** Get localized weapon description by WeaponType name */
    fun getWeaponDesc(weaponName: String, lang: String): String {
        val key = "desc_${weaponName.lowercase()}"
        return getString(key, lang)
    }

    /** Get localized upgrade description. Abbreviation: mm, lr, fb, is, pc, bd, os, ds */
    fun getUpgradeDesc(abbrev: String, tier: Int, lang: String): String {
        val key = "upg_${abbrev}_$tier"
        return getString(key, lang)
    }

    /** Map WeaponType to its abbreviation for localization keys */
    fun weaponAbbrev(weaponName: String): String = when (weaponName) {
        "MAGIC_MISSILE" -> "mm"
        "LIGHTNING_RING" -> "lr"
        "FIREBALL" -> "fb"
        "ICE_SHARD" -> "is"
        "POISON_CLOUD" -> "pc"
        "BOOMERANG_DAGGER" -> "bd"
        "ORBITING_SHIELD" -> "os"
        "DIVINE_SPEAR" -> "ds"
        else -> "mm"
    }

